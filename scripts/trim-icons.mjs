// Builds src/styles/phosphor.generated.css: the Phosphor icon font CSS reduced to the icons the
// site actually references (every `ph-*` token found in src/) and to the woff2 font files.
// The full sheets define ~1,500 icons each, which is ~250 KB of render-blocking CSS.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const used = new Set();

const walk = (dir) => {
	for (const name of readdirSync(dir)) {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) walk(path);
		else if (/\.(astro|ts|js|mjs|mdx?|json|html)$/.test(name) && !name.endsWith(".generated.css")) {
			for (const match of readFileSync(path, "utf8").matchAll(/\bph-[a-z0-9]+(?:-[a-z0-9]+)*/g)) used.add(match[0]);
		}
	}
};
walk(join(root, "src"));

const weights = [
	{ dir: "regular", file: "Phosphor" },
	{ dir: "light", file: "Phosphor-Light" },
	{ dir: "fill", file: "Phosphor-Fill" },
];

let output = "/* Generated by scripts/trim-icons.mjs - do not edit. */\n";
let kept = 0;

for (const { dir, file } of weights) {
	const css = readFileSync(join(root, "node_modules/@phosphor-icons/web/src", dir, "style.css"), "utf8");
	const firstIcon = css.search(/^\.ph[a-z-]*\.ph-[a-z0-9-]+:before/m);
	let base = css.slice(0, firstIcon);
	base = base.replace(/src:[\s\S]*?;\n/, `src: url("../../node_modules/@phosphor-icons/web/src/${dir}/${file}.woff2") format("woff2");\n`);
	output += base;

	for (const rule of css.slice(firstIcon).matchAll(/^(\.ph[a-z-]*\.(ph-[a-z0-9-]+):before\s*\{[^}]*\})/gm)) {
		if (used.has(rule[2])) {
			output += `${rule[1]}\n`;
			kept++;
		}
	}
}

writeFileSync(join(root, "src/styles/phosphor.generated.css"), output);
console.log(`trim-icons: kept ${kept} icon rules, ${output.length} bytes`);
